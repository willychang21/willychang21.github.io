// Generates src/content/route-map.generated.ts: the dot-matrix land mask, graticule and
// great-circle legs for the route plate in the masthead. Run with `bun run generate:map`
// after changing a station or the plate's extent; the output is committed so d3-geo and
// the atlas never ship to the browser.
//
// Land data: Natural Earth 1:110m via the world-atlas package (public domain).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoContains, geoEquirectangular, geoInterpolate } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topology, topology.objects.land);

// A Pacific-centred plate carrée: Taipei sits on the left, the US on the right, so the
// route reads in the same direction as the page.
const CENTER_LON = -163;
const LON_SPAN = 184; // degrees shown, centred on CENTER_LON
const LAT_TOP = 72;
const LAT_BOTTOM = 6;
const UNIT = 6; // viewBox units per degree
const STEP = 1.5; // degrees between dots

const projection = geoEquirectangular()
	.rotate([-CENTER_LON, 0])
	.scale((180 / Math.PI) * UNIT)
	.translate([(LON_SPAN / 2) * UNIT, LAT_TOP * UNIT]);

const width = LON_SPAN * UNIT;
const height = (LAT_TOP - LAT_BOTTOM) * UNIT;
const round = (n) => Math.round(n * 10) / 10;

// Land mask: one hex string per row, one bit per dot, MSB first.
const cols = Math.floor(LON_SPAN / STEP);
const rows = Math.floor((LAT_TOP - LAT_BOTTOM) / STEP);
const mask = [];
for (let r = 0; r < rows; r++) {
	const lat = LAT_TOP - (r + 0.5) * STEP;
	let bits = '';
	for (let c = 0; c < cols; c++) {
		const lon = CENTER_LON - LON_SPAN / 2 + (c + 0.5) * STEP;
		bits += geoContains(land, [lon, lat]) ? '1' : '0';
	}
	bits = bits.padEnd(Math.ceil(cols / 4) * 4, '0');
	let hex = '';
	for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4), 2).toString(16);
	mask.push(hex);
}

// Stations: city-centre coordinates and their airport codes.
const stations = [
	{ id: 'tpe', code: 'TPE', city: 'Taipei', lon: 121.56, lat: 25.03 },
	{ id: 'sea', code: 'SEA', city: 'Seattle', lon: -122.33, lat: 47.61 },
	{ id: 'cmi', code: 'CMI', city: 'Champaign', lon: -88.24, lat: 40.11 },
	{ id: 'sjc', code: 'SJC', city: 'San Jose', lon: -121.89, lat: 37.34 }
].map((s) => {
	const [x, y] = projection([s.lon, s.lat]);
	return { ...s, x: round(x), y: round(y) };
});

// Each leg follows the great circle, sampled densely enough to read as a curve.
function leg(a, b) {
	const interpolate = geoInterpolate([a.lon, a.lat], [b.lon, b.lat]);
	const points = Array.from({ length: 65 }, (_, i) => projection(interpolate(i / 64)));
	return points.map(([x, y], i) => `${i ? 'L' : 'M'}${round(x)} ${round(y)}`).join('');
}
// One leg per move, in order.
const legs = stations.slice(1).map((to, i) => ({ from: stations[i].id, to: to.id, d: leg(stations[i], to) }));

// Graticule every 30° of longitude and 20° of latitude, with labels.
const meridians = [];
for (let lon = -270; lon <= 0; lon += 30) {
	const [x] = projection([lon, 0]);
	if (x < 1 || x > width - 1) continue;
	const norm = ((lon + 540) % 360) - 180;
	const label = norm === 180 || norm === -180 ? '180°' : `${Math.abs(norm)}°${norm < 0 ? 'W' : 'E'}`;
	meridians.push({ x: round(x), label });
}
const parallels = [20, 40, 60].map((lat) => ({ y: round(projection([CENTER_LON, lat])[1]), label: `${lat}°N` }));

const out = `// Generated by scripts/generate-route-map.mjs. Do not edit by hand.
// Land: Natural Earth 1:110m (public domain) via world-atlas.

export const routeMap = ${JSON.stringify({ width, height, step: STEP * UNIT, cols, mask, stations, legs, meridians, parallels }, null, '\t')} as const;
`;
writeFileSync(new URL('../src/content/route-map.generated.ts', import.meta.url), out);
console.log(`route map: ${cols}×${rows} dots, ${(out.length / 1024).toFixed(1)} KiB`);
